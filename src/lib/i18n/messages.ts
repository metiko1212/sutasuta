export type MessageKey = keyof typeof MESSAGES;

type Vars = Record<string, string | number>;

/** Fills {placeholders}. Unknown names are left alone so they are easy to spot. */
function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const pair = MESSAGES[key] as readonly [string, string] | undefined;
  if (!pair) return key;
  // Amharic falls back to English when a string is deliberately left empty.
  const value = locale === "am" ? pair[1] || pair[0] : pair[0];
  return interpolate(value, vars);
}

export type Translator = (key: MessageKey, vars?: Vars) => string;

/** `const t = makeT(locale)` — the shape every page and component expects. */
export function makeT(locale: Locale): Translator {
  return (key, vars) => translate(locale, key, vars);
}
